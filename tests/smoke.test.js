import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const app=readFileSync(new URL('../src/app.js',import.meta.url),'utf8');
const cap=JSON.parse(readFileSync(new URL('../capacitor.config.json',import.meta.url),'utf8'));
test('app is Persian and RTL',()=>{assert.match(html,/<html lang="fa" dir="rtl">/);});
test('offline storage and exports are implemented',()=>{assert.match(app,/localStorage/);assert.match(app,/padnakasht-backup/);assert.match(html,/exportCsv/);});
test('native app configuration points to built web assets',()=>{assert.equal(cap.webDir,'dist');assert.equal(cap.appId,'com.padnakasht.kimi');});
test('core business modules are present',()=>{for(const label of ['مشتری','محصول','فاکتور','تراکنش','یادداشت'])assert.ok(html.includes(label));for(const id of ['customerForm','productForm','invoiceForm','paymentForm'])assert.ok(html.includes('id="'+id+'"'));});
